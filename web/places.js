export function parseCoords(text) {
  const match = String(text || "").trim().match(/^(-?\d+(?:\.\d+)?)\s*[, ]\s*(-?\d+(?:\.\d+)?)$/);
  if (!match) return null;
  const lat = Number(match[1]);
  const lon = Number(match[2]);
  if (lat < -90 || lat > 90 || lon < -180 || lon > 180) return null;
  return { lat, lon, name: roundName(lat, lon) };
}

function roundName(lat, lon) {
  return lat.toFixed(1) + ", " + lon.toFixed(1);
}

export function findPlaces(query) {
  const words = String(query || "").trim().toLowerCase();
  if (words.length < 2 || parseCoords(words)) return [];
  return PLACES.filter((place) => place[0].toLowerCase().includes(words)).slice(0, 6)
    .map(([name, lat, lon, tz]) => ({ name, lat, lon, tz }));
}
