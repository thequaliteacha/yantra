export function parseCoords(text) {
  const match = String(text || "").trim().match(/^(-?\d+(?:\.\d+)?)\s*[, ]\s*(-?\d+(?:\.\d+)?)$/);
  if (!match) return null;
  const lat = Number(match[1]);
  const lon = Number(match[2]);
  if (lat < -90 || lat > 90 || lon < -180 || lon > 180) return null;
  return { lat, lon, name: roundName(lat, lon) };
}

function roundName(lat, lon) {
  return lat.toFixed(1) + ", " + lon.toFixed(1);
}

/* Accents fold away, so "Montréal" and "montreal" meet. */
function fold(text) {
  return String(text || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();
}

export function placeLabel(name, region) {
  return region ? name + ", " + region : name;
}

/* Matches by city or region, the way a person types a place: "austin",
   "austin tx", "austin, texas", "texas". A city that starts with the words
   comes before one that merely contains them; a match on the city name comes
   before a match on its region. Each result carries its full label. */
export function findPlaces(query) {
  const words = fold(query).replace(/,/g, " ").replace(/\s+/g, " ");
  if (words.length < 2 || parseCoords(words)) return [];
  const terms = words.split(" ").filter(Boolean);
  const scored = [];
  for (const [name, region, lat, lon, tz] of PLACES) {
    const city = fold(name);
    const area = fold(region);
    const label = city + " " + area;
    const code = STATE_CODES[area] || "";
    const fits = terms.every((term) => label.includes(term) || (code && term === code));
    if (!fits) continue;
    let rank = 3;
    if (city === words || label === words || city + " " + code === words) rank = 0;
    else if (city.startsWith(terms[0])) rank = 1;
    else if (city.includes(terms[0])) rank = 2;
    scored.push({ rank, name, region, lat, lon, tz, label: placeLabel(name, region) });
  }
  scored.sort((a, b) => a.rank - b.rank || a.name.localeCompare(b.name));
  return scored.slice(0, 6).map(({ name, region, lat, lon, tz, label }) => ({ name, region, lat, lon, tz, label }));
}

